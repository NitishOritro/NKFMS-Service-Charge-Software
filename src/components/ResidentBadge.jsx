//  ধার্য সার্ভিস চার্জ ছিল ৩,৫০০ টাকা (সাধারণ হার ১,৫০০)। নামের পাশে এই
//  ব্যাজটি বসলে কেন অঙ্ক আলাদা তা এক নজরেই বোঝা যায়; মাউস রাখলে টুলটিপে
