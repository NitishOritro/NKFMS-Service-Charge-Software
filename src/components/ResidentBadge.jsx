export function ResidentBadge({ flat, className = '' }) {
  if (!Calc.isResidentFlat(flat)) return null;

  return (
    <span
      className={`resident-badge ${className}`.trim()}
      title={Calc.residentNote(flat)}
      aria-label={Calc.residentNote(flat)}
    >
      বসবাসরত অবস্থায়
    </span>
  );
}
