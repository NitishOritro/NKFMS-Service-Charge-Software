-- ---------------------------------------------------------------------
--  ধাপ ১ — নতুন কলাম
--  মাসভিত্তিক বিশেষ হার রাখার জন্য, যেমন {"2024-08": 3500}
-- ---------------------------------------------------------------------
ALTER TABLE flats
  ADD COLUMN IF NOT EXISTS custom_rates jsonb;

COMMENT ON COLUMN flats.custom_rates IS
  'মাসভিত্তিক বিশেষ ধার্য হার। উদাহরণ: {"2024-08": 3500, "2024-09": 3500}। খালি হলে settings.rateHistory এর সাধারণ হার প্রযোজ্য।';


-- ---------------------------------------------------------------------
--  ধাপ ২ — বসবাসরত ৮ জন মালিকের হার বসানো
--
--    A-1  সুখেন্দ্র নাথ চন্দ
--    A-4  চিত্রলেখা বিশ্বাস      ← আগে কোডের তালিকায় ছিল না
--    B-2  গৌতম চন্দ্র মজুমদার
--    B-5  অশোক কুমার শীল
--    B-7  তপতী চক্রবর্তী
--    C-1  দর্শনা সরকার           ← আগে কোডের তালিকায় ছিল না
--    C-3  নমিতা রানী বাউল
--    C-8  নিলিমা দে
-- ---------------------------------------------------------------------
UPDATE flats
SET custom_rates = '{"2024-08": 3500, "2024-09": 3500}'::jsonb
WHERE id IN ('fA-1', 'fA-4', 'fB-2', 'fB-5', 'fB-7', 'fC-1', 'fC-3', 'fC-8');

--  ৮ সারি হালনাগাদ হওয়ার কথা।


-- ---------------------------------------------------------------------
--  ধাপ ৩ — PostgREST-কে নতুন কলামের খবর দেওয়া
