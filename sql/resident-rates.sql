-- ---------------------------------------------------------------------
--  ধাপ ৪ — মিলিয়ে দেখুন
-- ---------------------------------------------------------------------
SELECT flat_no, owner_name, custom_rates
FROM flats
WHERE custom_rates IS NOT NULL
ORDER BY serial;
--  প্রত্যাশিত: ৮ সারি, প্রতিটিতে {"2024-08": 3500, "2024-09": 3500}


