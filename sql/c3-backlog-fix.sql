-- ---- ব্লক ক ----------------------------------------------------------
--  JSON-এ এই ১০ মাসে স্পষ্ট করে ' - ' লেখা আছে, অর্থাৎ জমা হয়নি।
--  ডাটাবেজে ১,৫০০ করে বসানো আছে।            মোট মুছে যাবে: ৳১৫,০০০
-- ---------------------------------------------------------------------
DELETE FROM payments
WHERE flat_id = 'fC-3'
  AND month IN ('2025-07','2025-08','2025-09','2025-10',
                '2026-02','2026-03','2026-04','2026-05','2026-06','2026-07');


-- ---- ব্লক খ ----------------------------------------------------------
--  ⚠️  সাবধানে পড়ুন — এই ৪টি মাস JSON-এ একেবারেই নেই।
--      ' - ' লেখাও নেই, ঘরটাই অনুপস্থিত। অর্থাৎ JSON বলছে না যে
--      এখানে জমা হয়নি; JSON এই মাসগুলো নিয়ে চুপ।
--
--      "আগের ডাটা মুছে দিন" কথাটা ধরে এগুলোও মোছার জন্য রাখা হলো।
--      যদি জানুয়ারি–মার্চ ২০২৫ ও আগস্ট ২০২৬ এর জমা সত্যিই হয়ে থাকে,
--      তবে এই ব্লকটি চালাবেন না।           মোট মুছে যাবে: ৳৬,০০০
-- ---------------------------------------------------------------------
DELETE FROM payments
WHERE flat_id = 'fC-3'
  AND month IN ('2025-01','2025-02','2025-03','2026-08');


-- =====================================================================
--  ধাপ ৪ — নতুন এন্ট্রি
--
--  ✅ কিছুই বসাতে হচ্ছে না।
--     JSON-এর টাকাসহ ১১টি মাসই ডাটাবেজে আগে থেকেই আছে — টাকার অঙ্ক
--     এবং আদায়কারী, দুটোই হুবহু মেলে। তাই কোনো INSERT নেই।
--
--     যে ১১টি অক্ষত থাকছে:
--       2024-08  ৩,৫০০  বিমল চক্রবর্তী
--       2024-09  ৩,৫০০  বিমল চক্রবর্তী
--       2024-10  ১,৫০০  বিমল চক্রবর্তী
--       2024-11  ১,৫০০  বিমল চক্রবর্তী
--       2024-12  ১,৫০০  বিমল চক্রবর্তী
--       2025-04  ১,৫০০  (আদায়কারী নেই)
--       2025-05  ১,৫০০  (আদায়কারী নেই)
--       2025-06  ১,৫০০  (আদায়কারী নেই)
--       2025-11  ৪,০০০  শিশির কুমার দাস
--       2025-12  ১,৫০০  শিশির কুমার দাস
--       2026-01  ৩,০০০  শিশির কুমার দাস
-- =====================================================================


-- ---------------------------------------------------------------------
--  ধাপ ৫ — ফলাফল মিলিয়ে দেখুন
-- ---------------------------------------------------------------------
SELECT count(*) AS sari, sum(amount) AS mot_joma
FROM payments WHERE flat_id = 'fC-3';
--  ক + খ দুটোই চালালে  → সারি ১১, মোট জমা ২৪,৫০০
--  কেবল ক চালালে       → সারি ১৫, মোট জমা ৩০,৫০০

SELECT month, amount, collector_id
FROM payments WHERE flat_id = 'fC-3' ORDER BY month;


