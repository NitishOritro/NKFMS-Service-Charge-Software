-- ---------------------------------------------------------------------
--  ধাপ ২ — বদলানোর আগের অবস্থা দেখে নিন
-- ---------------------------------------------------------------------
SELECT month, amount, collector_id
FROM payments WHERE flat_id = 'fC-3' ORDER BY month;
--  প্রত্যাশিত: ২৫ সারি, মোট জমা ৪৫,৫০০


-- =====================================================================
--  ধাপ ৩ — মুছে ফেলা
--  দুটি আলাদা ব্লক। আপনি চাইলে কেবল ব্লক-ক চালাতে পারেন।
